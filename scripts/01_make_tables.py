"""Generate Stage 8 standalone tables for the simulation project."""

from __future__ import annotations

import csv
import json
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT))

from functions.response_regimes import response_regime_table


CONFIG_DIR = PROJECT_ROOT / "config"
TABLES_DIR = PROJECT_ROOT / "tables"


def latex_escape(value):
    text = str(value)
    replacements = {
        "\\": r"\textbackslash{}",
        "_": r"\_",
        "%": r"\%",
        "&": r"\&",
        "#": r"\#",
        "{": r"\{",
        "}": r"\}",
    }
    for old, new in replacements.items():
        text = text.replace(old, new)
    return text


def read_csv_dicts(path):
    with path.open("r", newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def write_csv(path, rows, fieldnames):
    with path.open("w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)


def write_latex_table(path, caption, label, columns, rows, package_comment, paste_comment):
    with path.open("w", encoding="utf-8") as fh:
        fh.write("% Standalone LaTeX table generated by scripts/01_make_tables.py\n")
        fh.write(f"% Required packages: {package_comment}\n")
        fh.write(f"% Suggested text for paper: {paste_comment}\n")
        fh.write("\\documentclass{article}\n")
        fh.write("\\usepackage[margin=0.8in]{geometry}\n")
        fh.write("\\usepackage{booktabs}\n")
        fh.write("\\usepackage{array}\n")
        fh.write("\\begin{document}\n")
        fh.write("\\begin{table}[ht]\n\\centering\n")
        fh.write(f"\\caption{{{latex_escape(caption)}}}\n")
        fh.write(f"\\label{{{label}}}\n")
        fh.write("\\begin{tabular}{")
        fh.write("p{0.20\\linewidth}" * len(columns))
        fh.write("}\n\\toprule\n")
        fh.write(" & ".join(latex_escape(col) for col in columns))
        fh.write(" \\\\\n\\midrule\n")
        for row in rows:
            fh.write(" & ".join(latex_escape(row.get(col, "")) for col in columns))
            fh.write(" \\\\\n")
        fh.write("\\bottomrule\n\\end{tabular}\n")
        fh.write("\\end{table}\n")
        fh.write("\\end{document}\n")


def profile_rows(config):
    rows = []
    for name, spec in config["profiles"].items():
        rows.append(
            {
                "profile": name,
                "varies": ", ".join(spec["varies"]),
                "holds_constant": ", ".join(spec["holds_constant"]),
                "description": spec["description"],
            }
        )
    return rows


def main():
    TABLES_DIR.mkdir(exist_ok=True)
    with (CONFIG_DIR / "profile-definitions-v1.json").open("r", encoding="utf-8") as fh:
        config = json.load(fh)

    parameter_rows = read_csv_dicts(CONFIG_DIR / "parameter-ranges-v1.csv")
    write_csv(TABLES_DIR / "parameter-ranges-v1.csv", parameter_rows, parameter_rows[0].keys())
    write_latex_table(
        TABLES_DIR / "parameter-ranges-v1.tex",
        "Dimensionless baseline values and simulation ranges.",
        "tab:parameter-ranges-v1",
        ["parameter", "baseline", "range_min", "range_max", "role"],
        parameter_rows,
        "booktabs, array",
        "The simulation uses dimensionless baseline values and ranges; these are modelling controls, not calibrated estimates.",
    )

    response_rows = response_regime_table()
    response_fields = ["regime", "condition", "formula", "depends_on_z"]
    write_csv(TABLES_DIR / "response-regimes-v1.csv", response_rows, response_fields)
    write_latex_table(
        TABLES_DIR / "response-regimes-v1.tex",
        "Response-function regimes used in the first simulation.",
        "tab:response-regimes-v1",
        response_fields,
        response_rows,
        "booktabs, array",
        "Both asymptotic cases of the response function are simulated separately to expose the role of the resilience scale.",
    )

    profiles = profile_rows(config)
    profile_fields = ["profile", "varies", "holds_constant", "description"]
    write_csv(TABLES_DIR / "profile-definitions-v1.csv", profiles, profile_fields)
    write_latex_table(
        TABLES_DIR / "profile-definitions-v1.tex",
        "Structural profiles used to generate stock-dependence in the simulated surfaces.",
        "tab:profile-definitions-v1",
        profile_fields,
        profiles,
        "booktabs, array",
        "The three profiles isolate liquidity, resilience-response, and combined structural channels in the volatility closure.",
    )

    print("Generated Stage 8 tables.")


if __name__ == "__main__":
    main()

